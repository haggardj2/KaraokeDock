// Writes Gateway/public/themes.css from the shared themes in src/web/src/theme.ts, so the
// Gateway request page offers the same Midnight / Stage / Daylight palettes as Station.
// Run after changing a theme: node dev/sync-gateway-themes.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { DEFAULT_THEME_ID, THEMES } from '../src/web/src/theme.ts';

export const GATEWAY_THEMES_PATH = new URL('../Gateway/public/themes.css', import.meta.url);

export function renderGatewayThemesCss() {
  const blocks = THEMES.map((theme) => {
    // data-theme-scope lets one element (e.g. a theme picker swatch) preview another theme.
    const selector = [
      ...(theme.id === DEFAULT_THEME_ID ? [':root'] : []),
      `:root[data-theme="${theme.id}"]`,
      `[data-theme-scope="${theme.id}"]`,
    ].join(',\n');
    const tokens = Object.entries(theme.tokens).map(([name, value]) => `  --color-${name}: ${value};`);
    return `${selector} {\n  color-scheme: ${theme.scheme};\n${tokens.join('\n')}\n}`;
  });
  return `/* Generated by dev/sync-gateway-themes.mjs from src/web/src/theme.ts — do not edit by hand. */\n\n${blocks.join('\n\n')}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(GATEWAY_THEMES_PATH, renderGatewayThemesCss());
  console.log(`Wrote ${fileURLToPath(GATEWAY_THEMES_PATH)}`);
}
